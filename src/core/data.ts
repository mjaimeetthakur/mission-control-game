export function createDesign(missionId: MissionId): SpacecraftDesign {
  const mission = missions.find((m) => m.id === missionId);
  if (!mission) throw new Error("Unknown mission scenario.");
  const deep = missionId === "mars" || missionId === "asteroid";
  const lunar = missionId === "moon";
  const componentIds =
    deep || lunar
      ? [
          "bus-deep",
          "camera",
          "spectrometer",
          ...(missionId === "asteroid" ? ["magnetometer"] : []),
          deep ? "solar-large" : "solar-compact",
          "battery-large",
          "propulsion-bi",
          "antenna-high",
          "computer-hardened",
          "thermal-active",
          "attitude-precision",
          "structure-heavy",
          "redundancy-full",
        ]
      : [
          "bus-light",
          "camera",
          "solar-compact",
          "battery-small",
          "propulsion-mono",
          "antenna-low",
          "computer-standard",
          "thermal-passive",
          "attitude-basic",
          "structure-light",
          "redundancy-basic",
        ];
  const now = new Date().toISOString();
  return {
    id: crypto.randomUUID(),
    name: `${mission.name} · 01`,
    missionId,
    componentIds,
    fuelKg:
      missionId === "earth"
        ? 80
        : lunar
          ? 450
          : missionId === "mars"
            ? 650
            : 950,
    vehicleId:
      missionId === "earth"
        ? "swift"
        : missionId === "asteroid"
          ? "titan"
          : "atlas",
    altitudeKm: mission.defaultAltitudeKm,
    inclinationDeg: missionId === "earth" ? 97 : 90,
    seed: 2026,
    schemaVersion: 1,
    createdAt: now,
    updatedAt: now,
  };
}
